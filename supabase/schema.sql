  id bigint primary key,
  type text not null,
  sujet text not null,
  description text not null,
  trajet text not null,
  date timestamptz not null,
  status text not null,
  "autreCategorie" text,
  "imagePath" text,
  "audioPath" text,
  "aiConseil" text,
  responses jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

