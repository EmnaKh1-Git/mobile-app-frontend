-- Temporary compatibility policies. Replace broad policies with per-user
-- policies after all clients use Supabase Auth sessions.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles', 'trajets', 'trajet_etapes', 'lieux', 'planning',
    'msg_conversation', 'msg_membre', 'msg_message'
  ] loop
    execute format('drop policy if exists "%s anon access" on public.%I', table_name, table_name);
    execute format(
      'create policy "%s anon access" on public.%I for all to anon, authenticated using (true) with check (true)',
      table_name, table_name
    );
  end loop;
end $$;

-- ============================================================
-- Module Trajets (Yassine) : réservations, discussions de trajet,
-- évaluations, alertes et options des trajets.
-- Mêmes tables que les bases SQLite discussions.db et complements.db
-- (lib/core/services/discussion_database.dart et complements_database.dart).
-- Les identifiants d'utilisateurs (passager_id, auteur_id, user_id…)
-- sont des bigint : idTrajetDe() dans lib/core/constants/app_constants.dart
-- les calcule à partir de profiles.local_id (« usr_1001 » → 1001).
-- ============================================================

create table if not exists public.passagers_trajet (
  id bigint generated by default as identity primary key,
  trajet_id bigint not null references public.trajets(id) on delete cascade,
  passager_id bigint not null,
  nom text not null default '',
  places integer not null default 1 check (places > 0),
  date_reservation timestamptz not null default now(),
  presence text not null default 'inconnue'
    check (presence in ('inconnue', 'present', 'absent'))
);
create index if not exists idx_passagers_trajet
  on public.passagers_trajet (trajet_id);

create table if not exists public.messages_trajet (
  id bigint generated by default as identity primary key,
  trajet_id bigint not null references public.trajets(id) on delete cascade,
  auteur_id bigint not null,
  auteur_nom text not null default '',
  texte text not null,
  type text not null default 'texte'
    check (type in ('texte', 'statut', 'systeme')),
  date timestamptz not null default now()
);
create index if not exists idx_messages_trajet
  on public.messages_trajet (trajet_id, date);

create table if not exists public.lectures_discussion (
  trajet_id bigint not null references public.trajets(id) on delete cascade,
  user_id bigint not null,
  lu_jusqu_a timestamptz not null,
  primary key (trajet_id, user_id)
);

create table if not exists public.evaluations_trajet (
  id bigint generated by default as identity primary key,
  trajet_id bigint not null references public.trajets(id) on delete cascade,
  auteur_id bigint not null,
  auteur_nom text not null default '',
  cible_id bigint not null,
  cible_nom text not null default '',
  note integer not null check (note between 1 and 5),
  commentaire text not null default '',
  date timestamptz not null default now(),
  unique (trajet_id, auteur_id, cible_id)
);

create table if not exists public.alertes_trajet (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  ville_depart text not null default '',
  ville_arrivee text not null default '',
  jour timestamptz,
  heure integer,
  moment text,
  places integer not null default 1,
  date_creation timestamptz not null default now()
);
create index if not exists idx_alertes_user on public.alertes_trajet (user_id);

create table if not exists public.options_trajet (
  trajet_id bigint primary key references public.trajets(id) on delete cascade,
  serie_id text,
  entre_filles boolean not null default false
);

alter table public.passagers_trajet enable row level security;
